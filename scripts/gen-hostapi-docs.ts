// Regenerates the built-in table in SPEC.md §8 from hostapi.json (decision A3: the registry
// generates the docs). Run: bun run gen:hostapi   (tests/unit/spec-sync.test.ts fails when stale)
import { HOST_FUNCTIONS, type HostFunction } from "../HostApi";

export const BEGIN = "<!-- hostapi:begin (generated by scripts/gen-hostapi-docs.ts; do not edit) -->";
export const END = "<!-- hostapi:end -->";

const signature = (fn: HostFunction) =>
  `\`${fn.name}(${fn.params.map((p) => (p.variadic ? `…${p.name}` : p.optional ? `${p.name}?` : p.name)).join(", ")})\``;
const types = (fn: HostFunction) =>
  fn.params.length === 0 ? "—" : fn.params.map((p) => `${p.name}: ${p.type.replace(/\|/g, " \\| ")}`).join(", ");
const cell = (s: string) => s.replace(/\|/g, "\\|");

export function renderTable(): string {
  const rows = (provider: "core" | "host") =>
    HOST_FUNCTIONS.filter((f) => f.provider === provider).map((f) =>
      provider === "core"
        ? `| ${signature(f)} | ${types(f)} | ${cell(f.returns)} | ${cell(f.doc)} |`
        : `| ${signature(f)} | ${types(f)} | ${cell(f.returns)} | \`${f.capability ?? ""}\` | ${cell(f.doc)} |`,
    );
  return [
    BEGIN,
    "",
    "**Core** (implemented by every runtime; no host needed):",
    "",
    "| Function | Parameters | Returns | Behaviour |",
    "| --- | --- | --- | --- |",
    ...rows("core"),
    "",
    "**Host** (supplied by the embedding host; `vmrun` alone returns `nil`):",
    "",
    "| Function | Parameters | Returns | Capability | Behaviour |",
    "| --- | --- | --- | --- | --- |",
    ...rows("host"),
    "",
    END,
  ].join("\n");
}

export function updateSpec(spec: string): string {
  const i = spec.indexOf(BEGIN);
  const j = spec.indexOf(END);
  if (i < 0 || j < 0) throw new Error("SPEC.md is missing the hostapi markers");
  return spec.slice(0, i) + renderTable() + spec.slice(j + END.length);
}

if (import.meta.main) {
  const path = new URL("../SPEC.md", import.meta.url).pathname;
  const spec = await Bun.file(path).text();
  await Bun.write(path, updateSpec(spec));
  console.log("SPEC.md §8 regenerated from hostapi.json");
}
